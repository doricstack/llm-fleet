#!/usr/bin/env python3
"""Keep the pane's version line in step with the one version this plugin has.

`plugins/llm-fleet/.claude-plugin/plugin.json` is the only place the version is
written. The two marketplace files carry none: the host reads the manifest's
version for an entry that sets none, and an entry that sets a different one only
earns a validation warning while the manifest still wins.

The pane is drawn by modules the host evaluates with no filesystem, so it cannot
read the manifest at runtime. `plugins/llm-fleet/components/version.ts` is therefore
generated from the manifest by this script and never edited by hand: run
`make version` after raising the version, and `make quality` refuses a tree whose
generated file no longer matches.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "plugins" / "llm-fleet" / ".claude-plugin" / "plugin.json"
MARKETS = (
    ROOT / ".claude-plugin" / "marketplace.json",
    ROOT / "plugins" / "llm-fleet" / ".claude-plugin" / "marketplace.json",
)
GENERATED = ROOT / "plugins" / "llm-fleet" / "components" / "version.ts"


def version() -> str:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))["version"]


def render(value: str) -> str:
    """The generated module, ending in one newline."""
    return (
        "/**\n"
        " * The version the pane names in its footer.\n"
        " *\n"
        " * Generated from plugins/llm-fleet/.claude-plugin/plugin.json by\n"
        " * scripts/version.py. Do not edit this file: change the manifest and run\n"
        " * `make version`.\n"
        " */\n"
        'export const PLUGIN_VERSION = "' + value + '";\n'
        "\n"
        "/** What the footer says: the plugin, who writes it, and the license. */\n"
        'export const FOOTER_TEXT = "llm-fleet " + PLUGIN_VERSION + " \\u00b7 Doric Stack LLC \\u00b7 MIT";\n'
    )


def marketplace_problems() -> list[str]:
    """A marketplace entry that sets a version, which the manifest already owns."""
    problems = []
    for path in MARKETS:
        document = json.loads(path.read_text(encoding="utf-8"))
        for entry in document.get("plugins", []):
            if "version" in entry:
                problems.append(
                    path.relative_to(ROOT).as_posix() + ": the entry sets version "
                    + str(entry["version"]) + "; the manifest is the one place"
                )
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Keep the pane's version line in step with the manifest.")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true",
                       help="write the generated module from the manifest")
    group.add_argument("--check", action="store_true",
                       help="fail when the generated module is out of date")
    options = parser.parse_args(argv)

    problems = marketplace_problems()
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1

    expected = render(version())
    current = GENERATED.read_text(encoding="utf-8") if GENERATED.exists() else ""
    if options.check:
        if current != expected:
            print(GENERATED.relative_to(ROOT).as_posix()
                  + " does not match the manifest; run `make version`", file=sys.stderr)
            return 1
        print("Version " + version() + " is written once and the pane matches it.")
        return 0
    if current == expected:
        print("Version " + version() + " already matches the generated module.")
        return 0
    GENERATED.write_text(expected, encoding="utf-8")
    print("Wrote " + GENERATED.relative_to(ROOT).as_posix() + " for version " + version() + ".")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
