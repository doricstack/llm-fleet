#!/usr/bin/env python3
"""The plugin's types contract names every `$.state` key its modules use.

`claude plugin validate` refuses a plugin whose hooks module reads or writes a
`$.state` key that the manifest's types contract does not declare in
`interface PluginState { "llm-fleet": { ... } }`. CI has no host CLI, so that check
cannot run there (`make plugin-validate` runs it where one is installed). This
holds the same rule from the source: the manifest names a contract that exists,
every literal key the plugin's modules hand to `$.state` is declared in it, and a
`$.state` call whose key is not a literal is refused, because a key this test
cannot read is a key nobody can check.
"""

import json
from pathlib import Path
import re
import unittest


ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "llm-fleet"
MANIFEST = PLUGIN / ".claude-plugin" / "plugin.json"
# Generated by the host when it loads the plugin; never read as this plugin's source.
GENERATED = ".claude-plugin"
CALL = re.compile(r"\$\.state\.(?:get|set)\(")
# Any reach for `$.state`, however spaced; each must be one of the CALL forms.
ACCESS = re.compile(r"\$\s*\.\s*state\b")
PAIR = r"""\{\s*plugin:\s*["'](?P<plugin>[\w-]+)["']\s*,\s*key:\s*["'](?P<key>\w+)["']\s*,?\s*\}"""
# The one form of reference read: a module-level const holding the literal pair
# `as const`, the statement ending there. The host reads the same form.
REFERENCE = re.compile(r"^(?:export\s+)?const\s+(?P<name>\w+)\s*=\s*" + PAIR + r"\s*as\s+const\s*;",
                       re.MULTILINE)
NAMED = re.compile(r"\$\.state\.(?:get|set)\(\s*(?P<name>\w+)\s*[,)]")
# After one of these, a `/` opens a regular expression rather than dividing.
REGEX_AFTER = set("(,=:[!&|?{};+-*%<>~^")
REGEX_KEYWORDS = {"return", "typeof", "case", "in", "of", "delete", "void", "throw", "new",
                  "else", "yield", "await"}


def regex_end(text: str, start: int) -> int:
    """The index after the regular expression literal opening at `start`, flags included."""
    index = start + 1
    in_class = False
    while index < len(text) and text[index] != "\n":
        char = text[index]
        if char == "\\":
            index += 2
            continue
        if char == "[":
            in_class = True
        elif char == "]":
            in_class = False
        elif char == "/" and not in_class:
            index += 1
            while index < len(text) and text[index].isalpha():
                index += 1
            return index
        index += 1
    return index


def code_positions(text: str) -> tuple[list[bool], list[int]]:
    """For each character, whether it is code, and the brace depth it sits at.

    Comments, strings, regular expression literals and a template literal's text
    are not code; the expression inside a template's `${...}` is code again, so a
    call written there is still read.
    """
    code = [True] * len(text)
    depths = [0] * len(text)
    # Each entry is a template literal, holding the brace depth of its `${` when inside one.
    templates: list[int] = []
    depth = 0
    last = ""
    index = 0
    while index < len(text):
        char = text[index]
        pair = text[index:index + 2]
        depths[index] = depth
        if templates and templates[-1] < 0:
            # Inside a template literal's text.
            code[index] = False
            if char == "\\":
                if index + 1 < len(text):
                    code[index + 1] = False
                index += 2
                continue
            if pair == "${":
                code[index + 1] = False
                templates[-1] = depth
                depth += 1
                last = "{"
                index += 2
                continue
            if char == "`":
                templates.pop()
                last = "`"
            index += 1
            continue
        end = index
        if pair == "//":
            end = text.find("\n", index)
            end = len(text) if end < 0 else end
        elif pair == "/*":
            end = text.find("*/", index + 2)
            end = len(text) if end < 0 else end + 2
        elif char in "\"'":
            end = index + 1
            while end < len(text) and text[end] != char and text[end] != "\n":
                end += 2 if text[end] == "\\" else 1
            end = min(end + 1, len(text))
            last = char
        elif char == "/" and (not last or last in REGEX_AFTER or last in REGEX_KEYWORDS):
            end = regex_end(text, index)
            last = "/"
        if end > index:
            code[index:end] = [False] * (end - index)
            for position in range(index, min(end, len(text))):
                depths[position] = depth
            index = end
            continue
        if char == "`":
            code[index] = False
            templates.append(-1)
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if templates and templates[-1] == depth:
                # The `}` closing a `${`: back to the template's text.
                code[index] = False
                templates[-1] = -1
        if not char.isspace():
            if char.isalnum() or char in "_$":
                word = re.match(r"[\w$]+", text[index:])
                last = word.group(0) if word else char
                for position in range(index, index + len(last)):
                    depths[position] = depth
                index += len(last)
                continue
            last = char
        index += 1
    return code, depths


def line_of(text: str, position: int) -> int:
    return text.count("\n", 0, position) + 1


def state_keys(text: str) -> tuple[set[tuple[str, str]], list[str]]:
    """The (plugin, key) pairs this source hands to `$.state`, and what it could not read.

    Every call names a reference declared once at module level, and the name is
    used nowhere else, so a parameter or local that shadows it, or an expression
    that passes it on, is refused rather than resolved to the declaration. This
    guards the plugin's own source in CI, which has no host; the host's own
    validation, which parses the module, stays the authority where it runs.

    It fails closed. Telling code from text in JavaScript needs a parser (a `/`
    after `)` may open a regular expression or divide), so the checks that guard
    against a hidden call read the raw text: every reach for the state, every
    escape and every use of a reference's name counts wherever it is written,
    and a misread can refuse an honest module but never pass a hidden key.
    """
    if ACCESS.search(text) is None:
        # Nothing here reaches for the state, so nothing here can hide a key.
        return set(), []
    code, depths = code_positions(text)
    unread: list[str] = []
    for escape in re.finditer(r"\\u", text):
        unread.append("an escaped identifier at line {0}".format(line_of(text, escape.start())))
    if unread:
        # An escaped name can be any name, so no reference in this module can be trusted.
        return set(), unread
    declared: dict[str, list[tuple[str, str]]] = {}
    for match in REFERENCE.finditer(text):
        if code[match.start("name")] and depths[match.start("name")] == 0:
            declared.setdefault(match.group("name"), []).append(
                (match.group("plugin"), match.group("key")))
    calls = {call.start() for call in CALL.finditer(text) if code[call.start()]}
    named: list[tuple[int, str | None]] = []
    for access in ACCESS.finditer(text):
        match = NAMED.match(text, access.start()) if access.start() in calls else None
        named.append((access.start(), match.group("name") if match else None))
    references: dict[str, tuple[str, str]] = {}
    for name, pairs in declared.items():
        if len(pairs) > 1:
            unread.append("{0} is declared more than once".format(name))
            continue
        uses = list(re.finditer(r"(?<![\w$]){0}(?![\w$])".format(re.escape(name)), text))
        named_calls = sum(1 for _, called in named if called == name)
        if len(uses) != 1 + named_calls:
            unread.append("{0} is used outside its declaration and $.state calls".format(name))
            continue
        references[name] = pairs[0]
    keys: set[tuple[str, str]] = set()
    for start, name in named:
        if name in references:
            keys.add(references[name])
        elif name not in declared:
            unread.append("line {0}".format(line_of(text, start)))
    return keys, unread


def block(text: str, opener: str) -> str | None:
    """The body of the first `opener {...}` in this text, braces balanced."""
    match = re.search(re.escape(opener) + r"\s*\{", text)
    if match is None:
        return None
    depth = 0
    for index in range(match.end() - 1, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[match.end():index]
    return None


def declared_keys(contract: str) -> set[tuple[str, str]]:
    """The (plugin, key) pairs a contract declares in `interface PluginState`."""
    state = block(contract, "interface PluginState")
    if state is None:
        return set()
    # Comments are dropped first, so a key named in prose is not read as declared.
    state = re.sub(r"/\*.*?\*/|//[^\n]*", "", state, flags=re.DOTALL)
    found: set[tuple[str, str]] = set()
    # A plugin is a member at depth zero and its keys are members at depth one,
    # so the members of an object type a key holds are not read as keys.
    depth = 0
    plugin = ""
    # A member may be quoted, as a plugin name with a hyphen must be.
    for token in re.finditer(r"""[{}]|["']?([\w-]+)["']?\s*\??\s*:""", state):
        if token.group(0) == "{":
            depth += 1
        elif token.group(0) == "}":
            depth -= 1
        elif depth == 0:
            plugin = token.group(1)
        elif depth == 1 and plugin:
            found.add((plugin, token.group(1)))
    return found


# A store key the entry spells once, as a module constant holding its literal.
STORE_KEY = re.compile(r'^export const \w+_KEY = "([\w.:-]+)";', re.MULTILINE)


def store_keys(contract: str) -> set[str]:
    """The keys a contract declares in `interface FleetStore`, comments aside."""
    store = block(contract, "interface FleetStore")
    if store is None:
        return set()
    store = re.sub(r"/\*.*?\*/|//[^\n]*", "", store, flags=re.DOTALL)
    return set(re.findall(r"""^\s*["']([\w.:-]+)["']\s*\??\s*:""", store, flags=re.MULTILINE))


class ContractReading(unittest.TestCase):
    """The two readers, on text written here, so a reader that misses fails by name."""

    def test_a_reference_is_read_across_a_line_break(self) -> None:
        keys, unread = state_keys('const FOLDED = {\n  plugin: "fleet",\n  key: "folded",\n} as const;\n'
                                  'void $.state.set(FOLDED,\n  value)')
        self.assertEqual(keys, {("fleet", "folded")})
        self.assertEqual(unread, [])

    def test_an_inline_pair_is_refused_since_every_call_names_the_reference(self) -> None:
        keys, unread = state_keys('void $.state.set({ plugin: "fleet", key: "folded" }, value)\n')
        self.assertEqual(keys, set())
        self.assertEqual(unread, ["line 1"])

    def test_a_reference_shadowed_by_a_parameter_is_refused(self) -> None:
        text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                'function read(FOLDED) {\n  return $.state.get(FOLDED);\n}\n')
        keys, unread = state_keys(text)
        self.assertEqual(keys, set())
        self.assertEqual(unread, ["FOLDED is used outside its declaration and $.state calls"])

    def test_a_reference_used_in_an_expression_is_refused(self) -> None:
        text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                'const other = FOLDED;\nvoid $.state.get(FOLDED);\n')
        keys, unread = state_keys(text)
        self.assertEqual(keys, set())
        self.assertEqual(unread, ["FOLDED is used outside its declaration and $.state calls"])

    def test_a_reference_declared_in_a_comment_is_not_a_reference(self) -> None:
        for comment in ('/* const FOLDED = { plugin: "llm-fleet", key: "folded" } as const; */\n',
                        '// const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'):
            with self.subTest(comment=comment.split()[0]):
                keys, unread = state_keys(comment + 'void $.state.get(FOLDED);\n')
                self.assertEqual(keys, set())
                self.assertEqual(unread, ["line 2"])

    def test_a_declaration_that_continues_past_as_const_is_refused(self) -> None:
        text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const ? a : b;\n'
                'void $.state.get(FOLDED);\n')
        keys, unread = state_keys(text)
        self.assertEqual(keys, set())
        self.assertEqual(unread, ["line 2"])

    def test_a_reference_declared_twice_is_refused(self) -> None:
        text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                'const FOLDED = { plugin: "llm-fleet", key: "other" } as const;\n'
                'void $.state.get(FOLDED);\n')
        keys, unread = state_keys(text)
        self.assertEqual(keys, set())
        self.assertIn("FOLDED is declared more than once", unread)

    def test_a_regex_literal_holding_a_quote_hides_nothing_after_it(self) -> None:
        text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                "const re = /'/; $.state.get({ plugin: \"llm-fleet\", key: \"missing\" });\n"
                'void $.state.get(FOLDED);\n')
        keys, unread = state_keys(text)
        self.assertEqual(keys, {("llm-fleet", "folded")})
        self.assertEqual(unread, ["line 2"])

    def test_an_escaped_identifier_is_refused(self) -> None:
        text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                'function read(\\u0046OLDED) { return $.state.get(FOLDED); }\n')
        keys, unread = state_keys(text)
        self.assertIn("an escaped identifier at line 2", unread)
        self.assertNotIn(("llm-fleet", "folded"), keys)

    def test_state_reached_in_any_other_form_is_refused(self) -> None:
        for line in ('$.state.get ({ plugin: "llm-fleet", key: "missing" });\n',
                     'const s = $.state; s.get(FOLDED);\n',
                     '$ . state . set(FOLDED, value);\n'):
            with self.subTest(line=line):
                keys, unread = state_keys(
                    'const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n' + line)
                self.assertIn("line 2", unread)
                self.assertEqual(keys, set())

    def test_a_declaration_inside_a_function_is_not_module_level(self) -> None:
        text = ('function read() {\nconst FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                'return $.state.get(FOLDED);\n}\n')
        keys, unread = state_keys(text)
        self.assertEqual(keys, set())
        self.assertEqual(unread, ["line 3"])

    def test_a_mention_of_the_state_in_a_comment_or_string_is_refused(self) -> None:
        # Fail closed: the reader cannot always tell code from text, so a reach for
        # the state it does not read as a call is refused wherever it is written.
        for mention in ('const url = "https://example.test/$.state.get(x)";\n', '// $.state.set(y)\n'):
            with self.subTest(mention=mention):
                text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                        + mention + 'void $.state.get(FOLDED);\n')
                keys, unread = state_keys(text)
                self.assertEqual(unread, ["line 2"])
                self.assertEqual(keys, {("llm-fleet", "folded")})

    def test_a_regex_after_a_condition_hides_nothing(self) -> None:
        text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                "if (enabled) /'/.test(text) && $.state.set({ plugin: \"llm-fleet\", key: \"missing\" }, true);\n"
                'void $.state.get(FOLDED);\n')
        keys, unread = state_keys(text)
        self.assertIn("line 2", unread)
        self.assertNotIn(("llm-fleet", "missing"), keys)

    def test_a_shadow_on_a_line_the_reader_misreads_is_still_counted(self) -> None:
        text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                "if (on) /'/; function read(FOLDED) {\n  return $.state.get(FOLDED);\n}\n")
        keys, unread = state_keys(text)
        self.assertEqual(keys, set())
        self.assertEqual(unread, ["FOLDED is used outside its declaration and $.state calls"])

    def test_a_key_passed_by_reference_is_refused_with_its_line(self) -> None:
        keys, unread = state_keys('const a = 1;\nvoid $.state.get(ref)\n')
        self.assertEqual(keys, set())
        self.assertEqual(unread, ["line 2"])

    def test_a_named_literal_reference_is_read_wherever_it_is_used(self) -> None:
        text = ('const FOLDED = { plugin: "llm-fleet", key: "folded" } as const;\n'
                'void $.state.get(FOLDED);\nvoid $.state.set(FOLDED, value);\n')
        keys, unread = state_keys(text)
        self.assertEqual(keys, {("llm-fleet", "folded")})
        self.assertEqual(unread, [])

    def test_a_reference_not_declared_as_a_literal_is_refused(self) -> None:
        # Built at run time, so neither this test nor the host can read its key.
        text = ('const FOLDED = { plugin: NAME, key: "folded" } as const;\n'
                'void $.state.get(FOLDED);\n')
        keys, unread = state_keys(text)
        self.assertEqual(keys, set())
        self.assertEqual(unread, ["line 2"])

    def test_a_contract_without_plugin_state_declares_nothing(self) -> None:
        self.assertEqual(declared_keys("export type Topo = { run: string };\n"), set())

    def test_a_key_named_only_in_a_comment_is_not_declared(self) -> None:
        contract = ('declare module "claude-code" {\n  interface PluginState {\n'
                    '    fleet: {\n      /** folded: was here */\n      // open: too\n'
                    '      count: number;\n    };\n  }\n}\n')
        self.assertEqual(declared_keys(contract), {("fleet", "count")})

    def test_the_members_of_a_key_s_object_type_are_not_keys(self) -> None:
        contract = ('interface PluginState {\n  fleet: {\n    view: { width: number; open: boolean };\n'
                    '    folded: Record<string, boolean>;\n  };\n  other: { count: number };\n}\n')
        self.assertEqual(declared_keys(contract),
                         {("fleet", "view"), ("fleet", "folded"), ("other", "count")})

    def test_a_quoted_plugin_name_is_read(self) -> None:
        contract = 'interface PluginState {\n  "llm-fleet": {\n    folded: FleetFold;\n  };\n}\n'
        self.assertEqual(declared_keys(contract), {("llm-fleet", "folded")})


class FleetContract(unittest.TestCase):
    """The fleet plugin as committed."""

    def contract(self) -> str:
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
        named = manifest.get("types")
        self.assertIsInstance(named, str, "plugin.json names no types contract")
        path = (PLUGIN / named).resolve()
        self.assertIn(PLUGIN.resolve(), path.parents, "the contract lies outside the plugin folder")
        self.assertTrue(path.is_file(), "plugin.json names {0}, which is absent".format(named))
        return path.read_text(encoding="utf-8")

    def test_every_state_key_the_plugin_uses_is_declared(self) -> None:
        declared = declared_keys(self.contract())
        used: set[tuple[str, str]] = set()
        unread: list[str] = []
        for module in sorted(PLUGIN.rglob("*.ts")):
            if GENERATED in module.parts or module.name.endswith(".d.ts"):
                continue
            keys, lines = state_keys(module.read_text(encoding="utf-8"))
            used |= keys
            unread += ["{0} {1}".format(module.relative_to(PLUGIN).as_posix(), line) for line in lines]
        self.assertEqual(unread, [], "a $.state call whose key is not a literal")
        # A plugin with no state would make the comparison below pass on nothing.
        self.assertTrue(used, "no $.state key was read from the plugin's modules")
        self.assertEqual(sorted(used - declared), [], "used in $.state but not declared")
        # The host keeps a plugin's state under its manifest name and lets only
        # that plugin write it, so a key under another name is someone else's.
        name = json.loads(MANIFEST.read_text(encoding="utf-8"))["name"]
        self.assertEqual(sorted({plugin for plugin, _ in used}), [name],
                         "a $.state key outside the plugin's own name")
        self.assertEqual(sorted({plugin for plugin, _ in declared}), [name],
                         "the contract declares state outside the plugin's own name")

    def test_every_store_key_the_entry_names_is_declared(self) -> None:
        # The store is keyed by free text, which the host does not check, so the
        # contract is where a key and the shape it holds are written down: a key
        # the entry names and the contract does not is a value nobody can list.
        entry = (PLUGIN / "hooks" / "fleet.ts").read_text(encoding="utf-8")
        named = set(STORE_KEY.findall(entry))
        self.assertTrue(named, "no store key was read from the entry")
        declared = store_keys(self.contract())
        self.assertEqual(sorted(named - declared), [], "a store key the contract does not declare")
        self.assertEqual(sorted(declared - named), [], "a declared store key the entry never names")


if __name__ == "__main__":
    unittest.main()
